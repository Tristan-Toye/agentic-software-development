#!/usr/bin/env python3
"""Refresh the committed architecture map for a freshly cut stub and open the pull request into that stub.

    map_refresh_pr.py --root R --stub stub/2026-11-20 [--dry-run]
    map_refresh_pr.py --selftest

Run by `stub_target.py` right after it cuts a new stub (detached, never blocking the cut). The cut is the one moment
where "the integrated stub has merged and the new stub exists" is observable, and a pull request into the new stub is
the normal route for a change to reach development: nothing is ever pushed to development directly.

Steps: a temporary worktree on `origin/<stub>`, `vr_refresh.py` there (incremental: the cache lives in the git common
dir, which the worktree shares with R, and the previous extraction commit is read from `map-manifest.json`), then a
commit of `docs/architecture/` on `chore/map-refresh-<stub date>`, a push and `gh pr create --base <stub>`.

Opt-in: it acts only when the stub already carries `docs/architecture/map-manifest.json` or `crate-map.json` (a repo
that never ran `vr_map.py refresh` is left alone), or when ASD_MAP_REFRESH=1. ASD_MAP_REFRESH=0 turns it off.
Idempotent: an existing branch or open pull request of that name ends it quietly. Nothing changed means no pull
request. Exit 0 on done or skipped, 1 on a failure (the log says where). `ASD_GH_BIN` replaces gh;
`ASD_MAP_REFRESH_BIN` replaces the refresh command (it receives the worktree path).
"""
from __future__ import annotations

import argparse
import os
import shlex
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = "docs/architecture"
MARKERS = (DIR + "/map-manifest.json", DIR + "/crate-map.json")


def sh(cmd, cwd=None, timeout=None):
    try:
        p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.TimeoutExpired) as e:
        return 1, str(e)
    return p.returncode, (p.stdout if p.returncode == 0 else p.stdout + p.stderr).strip()


def gh(root, *args):
    return sh(shlex.split(os.environ.get("ASD_GH_BIN") or "gh") + list(args), cwd=root)


def enabled(root: str, stub: str) -> bool:
    flag = os.environ.get("ASD_MAP_REFRESH", "")
    if flag == "0":
        return False
    if flag == "1":
        return True
    return any(sh(["git", "-C", root, "cat-file", "-e", f"origin/{stub}:{m}"])[0] == 0 for m in MARKERS)


def run(root: str, stub: str, dry: bool = False, log=lambda m: print("map_refresh_pr: " + m, file=sys.stderr, flush=True)) -> int:
    root = os.path.abspath(root)
    if not enabled(root, stub):
        log("skipped: no committed map on %s (set ASD_MAP_REFRESH=1 to start one)" % stub)
        return 0
    branch = "chore/map-refresh-" + stub.split("/", 1)[-1]
    sh(["git", "-C", root, "fetch", "-q", "origin", stub])
    if sh(["git", "-C", root, "ls-remote", "--exit-code", "--heads", "origin", branch])[0] == 0:
        log("skipped: %s already exists on origin" % branch)
        return 0
    rc, out = gh(root, "pr", "list", "--head", branch, "--state", "all", "--json", "number", "--jq", "length")
    if rc == 0 and out.strip() not in ("", "0"):
        log("skipped: a pull request already exists for %s" % branch)
        return 0
    tmp = tempfile.mkdtemp(prefix="map-refresh-")
    wt = os.path.join(tmp, "wt")
    try:
        rc, out = sh(["git", "-C", root, "worktree", "add", "--detach", wt, f"origin/{stub}"])
        if rc != 0:
            log("worktree failed: " + out[:200])
            return 1
        cmd = shlex.split(os.environ.get("ASD_MAP_REFRESH_BIN") or "") or [sys.executable, os.path.join(HERE, "vr_refresh.py")]
        rc, out = sh(cmd + [wt, "--no-metrics"])
        log(out[-1500:] if out else "refresh produced no output")
        if rc != 0:
            log("refresh failed (exit %d)" % rc)
            return 1
        if not sh(["git", "-C", wt, "status", "--porcelain", "--", DIR])[1]:
            log("nothing changed: no pull request")
            return 0
        if dry:
            log("dry run: would open a pull request from %s into %s" % (branch, stub))
            return 0
        steps = [["git", "-C", wt, "checkout", "-q", "-b", branch],
                 ["git", "-C", wt, "add", "--", DIR],
                 ["git", "-C", wt, "commit", "-q", "-m", f"Refresh the architecture map for {stub}\n\nIncremental: recomputed from the previous extraction commit.\n"],
                 ["git", "-C", wt, "push", "-q", "origin", f"{branch}:refs/heads/{branch}"]]
        for c in steps:
            rc, out = sh(c)
            if rc != 0:
                log("%s failed: %s" % (c[3], out[:200]))
                return 1
        rc, out = gh(root, "pr", "create", "--base", stub, "--head", branch, "--title", f"Refresh the architecture map ({stub})",
                     "--body", "Regenerated by `vr_map.py refresh`, incrementally from the previous extraction commit "
                               "(see `docs/architecture/map-manifest.json`). Merge it into the stub like any dossier PR.")
        log("pull request: " + out[-300:] if rc == 0 else "gh pr create failed: " + out[:200])
        return 0 if rc == 0 else 1
    finally:
        sh(["git", "-C", root, "worktree", "remove", "--force", wt])
        shutil.rmtree(tmp, ignore_errors=True)


def selftest() -> int:
    bad: list[str] = []

    def check(name, ok):
        print(("ok   " if ok else "FAIL ") + name)
        if not ok:
            bad.append(name)

    with tempfile.TemporaryDirectory() as d:
        def g(*a, cwd=None):
            r = sh(["git", *a], cwd=cwd)
            return r[1]
        origin = os.path.join(d, "o.git"); w = os.path.join(d, "w")
        g("init", "-q", "--bare", "-b", "development", origin)
        g("init", "-q", "-b", "development", w)
        g("-C", w, "config", "user.email", "t@t"); g("-C", w, "config", "user.name", "t")
        g("-C", w, "remote", "add", "origin", origin)
        os.makedirs(os.path.join(w, DIR))
        open(os.path.join(w, DIR, "map-manifest.json"), "w").write("{}\n")
        g("-C", w, "add", "-A"); g("-C", w, "commit", "-q", "-m", "a")
        g("-C", w, "push", "-q", "origin", "development", "development:refs/heads/stub/2026-11-20")
        g("-C", w, "fetch", "-q", "origin")
        fake = os.path.join(d, "gh.sh")
        open(fake, "w").write('#!/bin/sh\necho "$@" >> "%s/gh.log"\ncase "$1 $2" in "pr list") echo 0;; "pr create") echo https://x/pull/1;; esac\n' % d)
        os.chmod(fake, 0o755)
        refr = os.path.join(d, "refresh.sh")
        open(refr, "w").write('#!/bin/sh\nmkdir -p "$1/%s"\necho "{\\"n\\": 1}" > "$1/%s/crate-map.json"\n' % (DIR, DIR))
        os.chmod(refr, 0o755)
        os.environ["ASD_GH_BIN"] = fake; os.environ["ASD_MAP_REFRESH_BIN"] = refr
        os.environ.pop("ASD_MAP_REFRESH", None)
        q = lambda m: None
        check("run:opens-a-pr", run(w, "stub/2026-11-20", log=q) == 0 and "pr create --base stub/2026-11-20" in open(d + "/gh.log").read())
        check("run:branch-pushed", sh(["git", "-C", w, "ls-remote", "--heads", "origin", "chore/map-refresh-2026-11-20"])[1] != "")
        n = open(d + "/gh.log").read().count("pr create")
        run(w, "stub/2026-11-20", log=q)
        check("run:idempotent", open(d + "/gh.log").read().count("pr create") == n)
        check("run:worktree-removed", "map-refresh-" not in sh(["git", "-C", w, "worktree", "list"])[1])
        os.environ["ASD_MAP_REFRESH"] = "0"
        check("env:off", not enabled(w, "stub/2026-11-20"))
        os.environ.pop("ASD_MAP_REFRESH")
        g("-C", w, "rm", "-q", "-r", DIR); g("-C", w, "commit", "-q", "-m", "rm")
        g("-C", w, "push", "-q", "origin", "development:refs/heads/stub/2026-11-27"); g("-C", w, "fetch", "-q", "origin")
        check("opt-in:no-map-no-action", not enabled(w, "stub/2026-11-27") and run(w, "stub/2026-11-27", log=q) == 0)
        os.environ["ASD_MAP_REFRESH"] = "1"
        check("env:on", enabled(w, "stub/2026-11-27"))
        os.environ.pop("ASD_MAP_REFRESH")
        os.environ["ASD_MAP_REFRESH_BIN"] = "true"
        g("-C", w, "push", "-q", "origin", "development:refs/heads/stub/2026-12-04"); g("-C", w, "fetch", "-q", "origin")
        os.environ["ASD_MAP_REFRESH"] = "1"
        n = open(d + "/gh.log").read().count("pr create")
        run(w, "stub/2026-12-04", log=q)
        check("nothing-changed:no-pr", open(d + "/gh.log").read().count("pr create") == n)
    print("all map_refresh_pr selftests passed" if not bad else "FAILED: " + ", ".join(bad))
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--root"); ap.add_argument("--stub"); ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if not a.root or not a.stub:
        ap.print_usage(sys.stderr)
        return 2
    return run(a.root, a.stub, a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
